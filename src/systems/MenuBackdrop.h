#pragma once

// ============================================================================
//  MenuBackdrop.h — 主菜单背后的"活着的地图"背景（2026-09-27）
//
//  ★ 负责人要求（原话）
//      "关于 UI 上加一个美化，主菜单界面（只有这个界面！），背景显示产生一个
//        半透明画面：地图上逐渐生成食物，然后蛇跑过去依次把这些食物吃掉。
//        这个画面要实际运行，蛇的 ai 就是扭动着向下一个食物前进。"
//
//  ★ 三个要点，逐条对应到实现
//      ① "半透明画面"   → 本类自己画一层底色，所有元素都带 alpha；
//                         MenuScene 先调 render() 再画菜单文字，
//                         于是文字压在动效之上。
//      ② "实际运行"     → 它【真的在推进】：食物逐个长出来、
//                         蛇真的在动、真的会吃掉、吃完了继续长。
//                         不是循环播放的动画贴图。
//      ③ "扭动着前进"   → 朝向用【有限转向速率】追目标（和真蛇一样有转弯半径），
//                         再叠一个正弦摆动 → 走出来的是一条蛇形曲线，不是直线。
//
//  ★ 为什么单独一个类而不是塞进 MenuScene
//     菜单场景的职责是"菜单"。把一段独立的仿真塞进去，
//     那一百多行会永远留在 MenuScene 里，以后谁也不敢动。
//     抽出来之后它自成一体：有自己的状态、自己的 update/render。
//
//  ★ 为什么不用真正的 Arena
//     用 Arena 就要配感知/大脑/碰撞/食物圈一大套，还得给玩家/AI 分身份 ——
//     为了一个背景动效引入这些，代价和风险都不对等
//     （而且 Arena 的世界是 3000²，得再套一层相机缩放）。
//     这里只要"看起来对"，所以用一个 100 行的小仿真。
//     ⚠️ 它的代码和数据与真正的游戏世界【完全隔离】——
//        绝不能被任何游戏逻辑读到（否则就是"第二份世界实现"，
//        那正是本项目反复踩的坑）。
// ============================================================================

#include <SFML/Graphics.hpp>
#include <cstddef>
#include <vector>

namespace systems {

class MenuBackdrop {
public:
    // 视口尺寸（= 窗口尺寸）。动效就在这块区域内发生。
    MenuBackdrop(float width, float height);

    // 推进动效。用真实 dt（不是固定步长）—— 它是表现层的东西，
    // 掉帧时慢一点没关系，不需要确定性。
    void update(float dt);

    // 画底色 + 食物 + 蛇 + 涟漪
    void render(sf::RenderWindow& window) const;

private:
    struct Food { float x = 0.0f, y = 0.0f, r = 0.0f; };

    // 吃掉食物时冒出来的一圈涟漪（强度从 1 衰减到 0）
    struct Ripple { float x = 0.0f, y = 0.0f, life = 0.0f; };

    void spawnFood();          // 随机位置长一个食物
    void pickNewTarget();      // 选"下一个要吃的食物"

    float m_w = 0.0f, m_h = 0.0f;

    // ---- 食物 ----
    std::vector<Food> m_foods;
    float m_spawnTimer = 0.0f;
    float m_spawnInterval = 0.55f;   // 每 0.55 秒长一个（"逐渐生成"）

    // ---- 蛇 ----
    float m_headX = 0.0f, m_headY = 0.0f;
    float m_heading = 0.0f;          // 当前朝向（弧度，不含摆动）
    float m_drawDir = 0.0f;          // 实际前进方向（含摆动）—— 画眼睛用它
    float m_wigglePhase = 0.0f;      // 摆动相位（"扭动"就是它）
    std::vector<sf::Vector2f> m_trail;   // 轨迹点（身体沿它铺）
    std::size_t m_targetIdx = 0;     // 正在追的食物下标
    bool  m_hasTarget = false;

    // -----------------------------------------------------------------------
    //  ★★ 运动参数（尺寸参数不在类里 —— 它们是 .cpp 里的 k* 常量）
    //
    //  ★ 为什么尺寸挪到 .cpp、运动留在这里
    //    尺寸必须"以游戏里的常量为基准 × 一个缩放系数"，
    //    所以它们和那段说明写在一起最容易核对（见 MenuBackdrop.cpp 顶部）。
    //    而运动参数是手感，放在成员里便于将来按需调。
    //
    //  ★ 这几个数是按【和游戏等比例】换算出来的，不是随手写的
    //    游戏：地图短边 3000、转向速率 8 rad/s → 每穿一次地图转 3000×8/250 = 96 rad
    //    背景：视口短边 720 → 等比例就是 720×?/165 = 96  →  ? ≈ 22 rad/s
    //    取 20（略小一点，看着更从容）。第一版写的 2.6 只有它的 1/8，
    //    所以蛇转得像在"漂"，那也是一眼看出不对的原因之一。
    // -----------------------------------------------------------------------
    float m_speed     = 165.0f;      // 像素/秒
    float m_turnRate  = 20.0f;       // 弧度/秒（和游戏等比例）
    float m_wiggleHz  = 1.9f;        // 摆动频率
    float m_wiggleAmp = 0.18f;       // 摆动幅度（弧度）—— 扭动要看得出来，但别转成圈

    std::vector<Ripple> m_ripples;

    // 专用的确定性随机（不用全局 rand()：菜单是可复现的表现层，
    // 而且动到全局序列会影响别的东西）
    unsigned m_rngState = 0x9E3779B9u;
    float rnd01();
    float rndRange(float lo, float hi);
};

}  // namespace systems
