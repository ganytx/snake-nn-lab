//  ★ 为什么要单独抽一个文件？
//
//  以前 loadConfig() 是一长串 `else if (key == "...")`，saveConfig() 又是一长串
//  `file << "..."`。两串必须【手工保持同步】，而实际上并没有：
//
//      · `teamBrains`（每队用什么算法）两个函数都【完全没提】
//        → 在“对局设置”里选好的算法，一重启就回到默认 rule
//      · 曾经还有 aiInitCount / aiMaxCount / aiSpawnInterval 三个字段
//        只写在结构体里，从此再也没有被人读过
//
//  这类 bug 的特点：**不会报错、不会崩**，只是“设了没用”。
//  靠人工核对的防线已经证明是失效的，所以改成一张表：
//
//      加一个配置项 = 在 GameConfigFields.h 里加一行，
//      字段声明 / 读配置 / 写配置 / 设置界面 就【同时】都有了
//
//  ⚠️ 字段表本身在 GameConfigFields.h，那个文件【故意不加 include guard】——
//     它是一张 X-macro 表，需要被重复展开。原因见该文件顶部注释。
// ============================================================================

