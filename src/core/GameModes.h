#pragma once

// ============================================================================
//  GameModes.h — 三个游戏模式的【唯一定义处】
//
//  ★ 为什么要有这个文件
//
//  「主菜单 → 开始游戏」现在进的是【模式选择页】，而三个模式各自有一套
//  默认参数（队数、每队几条、用什么算法、食物怎么产…）。
//
//  这些参数如果散在三个场景里各写一遍，就会出现这个项目反复踩的那类问题：
//    · 模式选择页的示意图按 A 参数画，实际开局按 B 参数跑
//    · 设置页改的是 C 参数，GameScene 读的是 D 参数
//  **所以"每个模式是什么"只在这里写一次**，其它地方一律读这张表。
//
//  ★ 三层配置（负责人 2026-09-26 定的职责边界，别搞混）
//
//      ① 通用世界规则（速度/转向/间距/饥饿/碰撞宽容/尸体…）
//         —— 三个模式共用，只在【主菜单 → 设置】里改
//      ② 每个模式的默认值（队数/每条数/算法/每队权重/食物速率）
//         —— 每个模式一份，在【主菜单 → 设置】里改，可 SAVE
//      ③ 这一局的配置（从 ② 拷一份，在【模式选择页 → 设置】里改）
//         —— **只影响这一局**，不存盘
//
//  本文件负责的是 ② 的【参数部分】；队伍算法/权重属于玩家选择，
//  由 GameConfig 的每模式结构体单独存（见 GameConfig::ModeConfig）。
// ============================================================================

#include <string>

// ⚠️⚠️ 前向声明必须放在 `namespace game` 【外面】！
//
//   `GameConfig` 是【全局命名空间】里的类型（定义在 core/Game.h）。
//   如果把这行写在 `namespace game {` 里面，它声明的是 `game::GameConfig` ——
//   一个【和全局那个完全不同的新类型】，于是 GameModes.cpp 里
//   `void applyModeParams(GameConfig&)` 会拿到一个只有声明、没有定义的
//   `game::GameConfig`，报 "invalid use of incomplete type"。
//   （2026-09-27 就这么挂了一次。）
struct GameConfig;

namespace game {

// ---------------------------------------------------------------------------
//  三个模式
//
//  ⚠️ 枚举值会被写进配置文件（mode_defaults 段），**顺序改了会让老配置错位**。
//     只允许在末尾追加。
// ---------------------------------------------------------------------------
enum class GameMode : int {
    ZoneRandom = 0,   // ① 随机食物圈
    Infinite   = 1,   // ② 无限模式（原玩法）
    Battle     = 2,   // ③ 大混战
};

inline constexpr int MODE_COUNT = 3;

// 三个模式的固定地图尺寸（负责人指定：统一 3000×3000）
inline constexpr float MODE_MAP_SIZE = 3000.0f;

// 玩家永远是【队 0 的第 0 条】—— 三个模式统一。
//
// ★ 为什么写成一个常量而不是散落的字面量 0
//   `playerTeam = 0` 这个约定同时被 Arena（造蛇时判 isHuman）、
//   GameScene（找 playerIndex）、模式定义三处依赖。
//   写成一个具名常量，改的时候只有一处。
inline constexpr int MODE_PLAYER_TEAM = 0;

// ---------------------------------------------------------------------------
//  模式的静态属性（名字 / 一句话 / 小字介绍）
//
//  ⚠️ 中文一律用【宽字符串】：sf::Text 不把窄字符串当 UTF-8，
//     而窄的 std::string 在界面里要过一次 textutil::utf8()。
//     这里直接给宽字符，调用方不用操心编码。
// ---------------------------------------------------------------------------
inline const wchar_t* modeName(GameMode m) {
    switch (m) {
        case GameMode::ZoneRandom: return L"随机食物圈";
        case GameMode::Infinite:   return L"无限模式";
        case GameMode::Battle:     return L"大混战";
    }
    return L"?";
}

// 一行标语（模式选择页标题下面那行）
//
// ★ 写法约定：**名词短语或陈述句，不用感叹、不用破折号抒情**
inline const wchar_t* modeTagline(GameMode m) {
    switch (m) {
        case GameMode::ZoneRandom: return L"两个食物圈，位置每轮随机";
        case GameMode::Infinite:   return L"无时间限制，蛇会持续加入";
        case GameMode::Battle:     return L"食物极少，靠击杀尸体维生";
    }
    return L"";
}

// 小字介绍（模式选择页下方那几行）
//
// ★ 写法约定：**陈述句、一行一件事、不出现"你/你的"**
//   （负责人要求："不要看上去像是某种对话，应该简洁，准确一些"）
//   每张介绍固定三行：玩法一句话 → 默认配置 → 关键机制或目标。
inline const wchar_t* modeDescription(GameMode m) {
    switch (m) {
        case GameMode::ZoneRandom:
            return L"地图上同时存在两个食物圈：一个正在供食，一个已定好位置、下一轮开。\n"
                   L"每轮结束后位置重新随机，背地图无效。\n"
                   L"默认 3 队 x 3 条：一队神经网络、一队神经网络、一队规则 AI。每队可加载不同权重。";
        case GameMode::Infinite:
            return L"食物全图随机生成，没有时间限制，没有队伍，所有蛇互为敌人。\n"
                   L"初始 5 条，每 7 秒加入一条，上限 20 条。开局就撒 200 个食物，场上最多 400 个。\n"
                   L"所有蛇的权重都从存档中随机选取。玩家蛇死亡后转为观战。";
        case GameMode::Battle:
            return L"食物极少：自然生成只有全图每秒 1 个，主要食物来源是死亡蛇留下的尸体。\n"
                   L"默认 5 队 x 3 条，全部为神经网络，权重可逐队指定。\n"
                   L"目标：击杀其他蛇并吃掉尸体，以维持饥饿值。";
    }
    return L"";
}

// ---------------------------------------------------------------------------
//  ★ 参数默认值（实现在 GameModes.cpp）
//
//  ★ 注意这里**不包含**队伍算法与权重 —— 那两个是玩家的选择，
//    存在 GameConfig::ModeConfig 里（因为要能逐队指定存档文件）。
//    本函数只负责"世界长什么样"。
//
//  ★ 为什么不返回一个结构体、而是直接写进 GameConfig
//    因为最终生效的就是 GameConfig 的对应字段；中间再加一层结构体
//    只会多一次"两边字段要保持同步"的机会 —— 本项目已经在这类事情上栽过。
// ---------------------------------------------------------------------------

// 把某个模式的【参数默认值】写进 cfg（只碰模式专属字段）
//
//  ⚠️ 它【不会】碰通用世界规则（速度/转向/饥饿/碰撞…）——
//     那些由 resetWorldRules() 负责。这样"玩家在大设置里改了速度"
//     不会被"开一局新模式"覆盖回去。
void applyModeParams(GameConfig& cfg, GameMode mode);

// 把【通用世界规则】恢复成基线值
//
//  ★ 只有两个地方该调它：
//      ① 主菜单设置页的「R 恢复初始默认设置」
//      ② 首次初始化配置（配置文件不存在时）
//    正常开局**不要**调，否则玩家改过的世界规则会被抹掉。
void resetWorldRules(GameConfig& cfg);

// 参数默认值的文字说明（设置页显示"这一项为什么是这个数"）
const wchar_t* modeParamNote(GameMode m);

}  // namespace game
