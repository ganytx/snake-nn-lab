#pragma once

// ============================================================================
//  Perception.h — 算法能"看到"的一切
//
//  ★ 接口的核心是「视野网格」VisionGrid
//    游戏把蛇头周围一定范围光栅化成一张 50x50 的格子图（随朝向旋转），
//    **算法自己决定怎么用**：可以直接拍平喂网络，也可以先从里面提取出
//    食物/敌人的位置、组成一个小向量再喂网络。
//
//    这个分工是有意的：网格是【感知】（像视网膜），
//    "该注意什么、怎么编码"是【算法】。分辨"这格是食物还是敌人"不算越界，
//    那和视网膜分辨颜色是一回事。
//
//  设计原则：受限 · 相对 · 有序 · 无分配
//
//    · 受限：只看得到视野网格覆盖的范围（外加最近 N 个队友的全局位置）。
//            "信息天花板"本身就是对局的核心实验变量——上帝视角下
//            "生存/捕猎/合作"这些目标都会退化成平凡解。
//    · 相对：网格以蛇头朝向为"上"，算法拿到的天然是相对自身的视角。
//    · 有序：辅助列表按距离由近到远排序。
//    · 无分配：Perception 由 Agent 持有并复用，每 tick 清空重填，
//              容器容量不释放 → 预热之后不再有任何堆分配。
// ============================================================================

#include "Types.h"
#include "VisionGrid.h"

#include <vector>

namespace arena {

// ---------------------------------------------------------------------------
//  自身状态
// ---------------------------------------------------------------------------
struct SelfState {
    int   id       = 0;
    int   teamId   = 0;
    Vec2  pos      = {};      // 世界坐标（规则 AI 的导航逻辑要用）
    float heading  = 0.0f;    // 绝对朝向（弧度）
    float speed    = 0.0f;
    int   length   = 0;       // 体节数
    bool  boosting = false;
    float hungerLeft = 0.0f;  // 距离饿死还剩几秒
    float headRadius = 0.0f;
    float bodyRadius = 0.0f;
    bool  alive    = true;
};

// ---------------------------------------------------------------------------
//  一条蛇的精简信息（辅助列表用，不是主要通道）
// ---------------------------------------------------------------------------
struct VisibleSnake {
    int   id         = 0;
    int   teamId     = 0;
    Vec2  headRel    = {};     // 相对位置 = 对方头 − 自己的头（世界轴对齐）
    float distance   = 0.0f;
    float bearing    = 0.0f;   // 相对自己朝向的方位角，0 = 正前方，[-π, π]
    float headingRel = 0.0f;   // 对方朝向 − 自己朝向，[-π, π]
    int   length     = 0;
    bool  boosting   = false;
    bool  alive      = true;
};

// ---------------------------------------------------------------------------
//  一个食物圈的精简信息（辅助通道 3）
// ---------------------------------------------------------------------------
struct FoodZoneView {
    Vec2  pos        = {};    // 圈心世界坐标
    float radius     = 0.0f;
    int   foodCount  = 0;     // 圈里现在有多少食物
    float distance   = 0.0f;  // 蛇头到圈心的距离（像素）
    float bearing    = 0.0f;  // 相对自己朝向的方位角，0 = 正前方，[-π, π]
    bool  active     = false; // 当前是否轮到它供食
    bool  occupied   = false; // 圈里现在有没有蛇（可选的额外信号）

    // ★ 这个圈本轮【还能供食几秒】（2026-09-26 新增）
    //
    //  ★ 为什么需要它
    //    规则 AI 要能"提前出发"：在供食结束【之前】就动身去下一个圈。
    //    只能等圈空了再走的话，永远迟到一步 —— 而空窗期有 5 秒，
    //    足够对手先到。
    //
    //  ★ 语义
    //      供食中 → 剩余供食秒数（> 0）
    //      空窗中 → 0（这个圈本轮没产出了）
    //      不活跃的圈 → 0
    //    ⚠️ 这是【时间】不是距离，属于世界常识（和"地图多大"一样），不是上帝视角。
    float supplySecondsLeft = 0.0f;

    // ★★ 这个圈现在要不要写进感知/画进画面（2026-09-26 引入，2026-09-27 改回恒 true）
    //
    //  ★ 它解决的问题（负责人报的现象）
    //    "一进游戏有两个圈，一个真圈一个假圈；假圈从始至终不产食物。"
    //
    //  ★ 两次改动方向相反，两次都要记
    //
    //    2026-09-26：供食期内把"下一个圈"设成 **不可见**。
    //      理由：那时圈的第 3 维是个**常量**（只表示"在哪个槽位"），
    //      观测里没有任何东西能告诉网络"这个圈现在还没开始供食"，
    //      于是"下一个圈"那 3 维就是**指向一块没有食物的空地**的错误信号。
    //
    //    2026-09-27：**改回恒为 true（永远可见）**。负责人原话：
    //      "下一个食物位置已经选好并出现" —— 如果"出现"只是给人看的、
    //      AI 看不到，那 AI 就**没法提前出发**去下一个圈。
    //
    //  ★ 2026-09-28 状态：观测已回滚到 29 维，"下一个圈"那 3 维的语义回到
    //    sin/cos(方位) + "是否轮到它供食"（恒 0），**没有距离维**了。
    //
    //    那么"提前看到下一个圈会不会又被指向空地"？—— 不会，靠的是
    //    【可见性】而不是【距离维】：
    //      · "哪里有可吃的食物" → `obs[8..15]` 的 8 个扇区，永远是**真实**的
    //      · "下一个圈在哪"     → `obs[23..25]`，只在**预告期**才可见
    //        （供食最后 3s + 整个空窗期），所以它出现时是真的该往那走
    //      · 非预告期 → 哨兵 (0, 0, 1) = "没有圈" = AI 看不到
    //    这条可见性规则是 33 维时代修的**真 bug**，回滚时特意保留了。
    //
    //  ★ 不这样改，"提前出发"在结构上不可能学会
    //    空窗期只有 5 秒，而圈间距是短边的 20%~30%（3000 图 = 600~900px，
    //    按 250px/s 要跑 2.4~3.6 秒）—— 只在空窗期才告知 = 刚够跑到、没有余量，
    //    那 3 维等于废掉。
    //
    //  ⚠️ 消费者必须与 PerceptionBuilder 保持一致：
    //     **渲染（GameScene）也画两个圈**，否则玩家看到的和 AI 看到的不再是同一个世界。
    bool  visible = true;
};

// ---------------------------------------------------------------------------
//  一帧的完整感知快照
// ---------------------------------------------------------------------------
struct Perception {
    SelfState self;

    // 世界常量："地图多大"算常识，所有蛇都知道，不算作弊
    float mapWidth  = 0.0f;
    float mapHeight = 0.0f;

    // ---- 主通道：视野网格 ----
    VisionGrid grid;
    float      cellSize = 32.0f;   // 每格边长（像素）：32 格 x 32px = 视野 1024 x 1024px

    int   tick = 0;
    float dt   = 0.0f;

    // ---- 辅助通道 1：视野内的其他蛇（按距离由近到远）----
    // 网格只有 2400px 且是量化的；这个列表给的是同范围内【精确】的位置、
    // 朝向、长度。算法想算精确的规避向量时用它更省事。
    std::vector<VisibleSnake> snakes;

    // ---- 辅助通道 2：最近的 N 个队友（不受视野限制）----
    // 存在的理由：网格只有 2400px 视野，视野外的队友完全看不见，
    // 而"合作"的前提是知道队友在哪。
    // N 是设置项，默认 2；实际数量可能少于 N（队友没那么多，或者已经死了）。
    // N = 0 即完全关闭队友全局感知 —— 这本身就是一个可研究的实验变量。
    std::vector<VisibleSnake> allies;

    // -----------------------------------------------------------------------
    //  ★ 当前 / 下一个要供食的圈的下标（−1 = 没有圈）
    //
    //  ★ 为什么要单独给"当前 + 下一个"，而不是把所有圈都给观测
    //
    //    旧做法是把"前 4 个圈"的方位写进观测 —— 那是一个**写死的数量假设**：
    //    圈数不是 4 的时候（1 个 / 6 个 / 0 个）它就不对了。
    //    改成"当前圈 + 下一个圈"之后，**观测与圈数彻底解耦**：
    //    不管世界里有几个圈，蛇看到的永远是
    //        "现在该去哪" + "接下来该去哪"。
    //
    //  ★ 为什么"下一个"也重要
    //    它让蛇有机会学【提前出发】：本轮快结束时先往下一个圈挪，
    //    而不是等当前圈关门了才开始跑。这是轮换玩法想要的预判行为。
    // -----------------------------------------------------------------------
    int activeZoneIndex = -1;
    int nextZoneIndex   = -1;

    // -----------------------------------------------------------------------
    //  ★ 碰撞风险 / 猎杀优势（给训练奖励用，不参与观测编码）
    //
    //  ★ 为什么不能只用"两蛇中心距"
    //
    //    规则是：**我的头**碰到**对方的身体**才死
    //    （CollisionSystem 里检的是 head vs other->getSegments()）。
    //    所以"两蛇离得近"这件事有两种完全相反的含义：
    //        我的头靠近对方身体 → 危险，要躲
    //        我的身体靠近对方头 → **猎杀优势**，要鼓励（包围就是这么形成的）
    //
    //    只用中心距会把这两件事混在一起 —— 既惩罚了危险，也惩罚了猎杀。
    //
    //  ★ 所以这里把两个方向分开算：
    //      headToEnemyBodyDist  —— 我的头 到 对方身体/头 的最近距离（危险）
    //      enemyHeadToMyBodyDist—— 对方头 到 我的身体 的最近距离（猎杀优势）
    //
    //  ★ 只在【视野内】算。视野外无法评估风险，也不该给信号。
    //  ★ 队友不算敌方 —— 队友之间本来就能互相穿过。
    // -----------------------------------------------------------------------
    bool  hasEnemyInView      = false;  // 视野内有没有敌人
    float headToEnemyBodyDist = 1.0e9f; // 我的头 → 最近敌方（身体或头）
    float enemyHeadToMyBodyDist = 1.0e9f; // 最近敌方头 → 我的身体
    int   riskEnemyId         = -1;     // 上面两个距离取自哪条敌人（蛇头到对方身体最近的那条）

    // -----------------------------------------------------------------------
    //  ★ 我的头到【最近地图边界】的距离（像素）
    //
    //  ★ 2026-09-26 新增，给 ⑪「危险距离扣分」用
    //
    //  ★ 为什么是"垂直距离"而不是从视野射线推
    //    视野里的墙射线只有【前/右/后/左】4 个正交方向，
    //    斜着冲向墙角时它们量不到真实的最近距离。
    //    而垂直距离（min(x, y, W−x, H−y)）是真实距离，
    //    也正是"离墙多近"的物理含义。而且它比跑一遍射线便宜得多。
    //
    //  ★ 语义 = "头【中心】到边界的距离"。
    //    碰撞判定是 head 半径顶到边界（见 CollisionSystem::checkWallCollision），
    //    所以真正"贴墙"时这个值约等于 headRadius(18px) 而不是 0 ——
    //    扣分公式用的是【线性比例】，差这 18px 只影响"贴死时是否为满额"，
    //    不影响单调性（越近扣越多）。
    //
    //  ★ 和 headToEnemyBodyDist 一样属于【每帧派生标量】，
    //    必须在 resetFrameState() 里重置，否则会冻结成陈旧值（缺陷 #45）。
    //
    //  ⚠️⚠️ 它挂在 **Perception** 下（本结构体），**不在 `SelfState` 里** ——
    //     所以访问是 `p.headToWallDist`，不是 `p.self.headToWallDist`。
    //     2026-09-26 就因为写成了 `p.self.headToWallDist` 而编译失败一次。
    //     ★ 原因值得记：`resetFrameState()` 里写的是【裸名字】
    //       `headToWallDist = 1e9f;`，从那一行完全看不出它属于哪一层；
    //       而它上面几行恰好是 `SelfState` 的自述字段，很容易误判。
    //     **加字段时的判据：它描述的是"蛇自己"还是"这一帧的外部世界"？**
    //       蛇自己的（半径/饥饿/朝向）→ SelfState
    //       外部世界的（敌人距离/墙距离/圈）→ Perception 本层
    //     "离墙多远"是外部几何，所以在本层。
    // -----------------------------------------------------------------------
    float headToWallDist = 1.0e9f;

    // ---- 辅助通道 3：食物圈（不受视野限制）----
    //
    // ★ 为什么圈要走"全局通道"而不是视野网格：
    //   圈是【地图结构】，不是"看到的东西"。蛇知道地图上有哪几个圈，
    //   这和"知道地图多大"一样属于常识。
    //   而且圈半径 150px、视野 1024px —— 如果只让它在视野里可见，
    //   蛇就永远学不会"提前往下一个圈移动"（那需要知道远处的圈在哪）。
    //
    // ★ 为什么这一条对学习是必需的：
    //   固定轮换顺序是【时间上的信息】，而 MLP 没有时钟、没有记忆。
    //   把 4 个圈的方位/距离/食物数都给它，"正在供食的圈食物最多"
    //   这一点就间接编码了"现在轮到谁"。
    std::vector<FoodZoneView> zones;

    // 清空所有列表但保留容量（下一 tick 复用，避免堆分配）
    void clearLists() {
        grid.clear();
        snakes.clear();
        allies.clear();
        zones.clear();
    }

    // -----------------------------------------------------------------------
    //  ★★★ 每帧开始时重置"本帧派生量"（2026-09-26 修一个严重 bug）
    //
    //  ★ 这个 bug 是什么
    //
    //    `clearLists()` 只清了**列表**，而下面这些**标量**每帧都不重置：
    //        hasEnemyInView / headToEnemyBodyDist / enemyHeadToMyBodyDist
    //    `PerceptionBuilder::build()` 开头只调了 `clearLists()`，
    //    于是**敌人一出视野，这几个读数就冻结在"最后一次看到它时的值"**。
    //
    //  ★ 它造成的实际后果（负责人亲眼观测到 + 实测确认）
    //
    //    规则 AI 的"成功脱离危险区"奖励（escape）**恒为 0**，因为：
    //        进入条件 距离 < 250px  → ✅ 会触发（冻结的读数恰好落在这个区间）
    //        退出条件 距离 > 375px  → ❌ **永远不触发**（读数冻在 250px 以下）
    //    实测：178 次进入危险区，**0 次成功退出**。
    //
    //    ⚠️ 这不只影响 escape —— 任何读这两个距离的逻辑都被污染：
    //       `RuleBrain::wantBoost()`（周围有没有敌人）、
    //       `RuleBrain::canHunt()`（围猎优势判定）、
    //       `EpisodeRunner` 里 ⑥⑦ 两项奖励的诊断。
    //
    //  ★ 修法
    //    在每帧构建感知之前调 `resetFrameState()`，把"本帧需要重新计算的量"
    //    恢复成中性值。语义上它等同于"这一帧还没看到任何敌人"。
    //
    //  ★ 为什么单独一个函数，而不是塞进 clearLists()
    //    `clearLists()` 的语义是"清列表"，而这里是"清派生标量" ——
    //    两者生命周期不同（列表靠容量复用，标量靠重算），混在一起会让人
    //    以后加字段时不知道该往哪边放。**分开写，名字即文档。**
    // -----------------------------------------------------------------------
    void resetFrameState() {
        hasEnemyInView          = false;
        headToEnemyBodyDist     = 1.0e9f;   // 哨兵 = "视野内没有敌人"
        enemyHeadToMyBodyDist   = 1.0e9f;
        riskEnemyId             = -1;
        headToWallDist          = 1.0e9f;   // ★ 同理：这一帧还没算，别留上一帧的值
        // ⚠️ activeZoneIndex / nextZoneIndex 由 Arena 每帧显式写，
        //    不在这里重置（复现"忘了写"就会读到上一帧的值，那是另一个坑）。
    }
};

}  // namespace arena
