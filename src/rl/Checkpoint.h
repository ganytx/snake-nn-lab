#pragma once

// ============================================================================
//  Checkpoint.h — 权重的「多版本存档」
//
//  ★ 负责人要的（原话）：
//      "每次我点开训练模式，训练的矩阵参数会保存吗？
//       我希望我能手动选择保存，并且可以加载多个版本的矩阵。"
//
//  ★ 先回答"会不会保存"：**之前不会。**
//    进训练模式每次都 `make_unique<rl::Trainer>(seed)` —— 网络用固定种子
//    重新初始化，练到一半按 ESC 或关窗口就全没了。
//    只有命令行 `train_probe` 会在跑完之后存一份 `train_probe_weights.txt`。
//
//  ★ 现在做成：
//      · 训练中随时按 S 存一份（文件名带局数和时间，不会互相覆盖）
//      · 按 L 加载一份（在列表里选）
//      · 存档放在 `build/saves/`（和 exe 同目录，跟着 build 走）
//
//  ★ 为什么文件名要带局数和时间戳
//    "多个版本"的关键是【能分辨哪个是哪个】。只存 `latest.txt` 的话，
//    存第二次就把第一次覆盖了，等于没有多版本。
//    带上 `ep000123_20260923_091500` 这样的标记之后，
//    文件列表本身就是一份"训练历程"，一眼能看出什么时候练到第几局。
//
//  ★ 文件格式直接复用 MLP::save() 的纯文本格式（见 src/nn/network.h）。
//    不用二进制：纯文本能肉眼对比、能 diff、能看出维度对不对 ——
//    这在"手写神经网络"的教学项目里比省几 KB 重要得多。
// ============================================================================

#include <filesystem>
#include <string>
#include <vector>

namespace ckpt {

// 存档目录。相对路径 —— 游戏和控制台程序都约定在 build\ 下运行。
inline const char* kDir = "saves";

// ---------------------------------------------------------------------------
//  ★ 退出训练模式时的【自动存档】文件名（2026-09-24 负责人要求）
//
//  ★ 为什么放在这里而不是 LiveTrainingScene 里
//    它是"存档约定"的一部分：训练模式【写】它，训练设置界面【显示】它
//    （用来告诉用户"这份是退出时自动存的"）。
//    放在 ckpt 里，两边都只依赖同一个定义 —— 不会出现"改了一处忘了另一处"。
//
//  ★ 固定名 + 每次覆盖
//    它表达的是"这次训练的最新进度"，语义上就该只有一份。
//    要留多个版本请用训练模式里按 S 自己命名（那套走 makeName）。
//    分工：auto_latest 用来"接着练"，命名存档用来"留档对比"。
// ---------------------------------------------------------------------------
inline const char* kAutoSaveName = "auto_latest.txt";

// 确保目录存在（已存在时什么都不做）
bool ensureDir();

// ★ UTF-8 字符串 → 文件系统路径
//
//  ⚠️ 绝对不要写 `std::filesystem::path(std::string)` —— 那个构造函数在
//     Windows 上按【本地代码页（GBK）】解释入参，中文文件名会变成乱码。
//     必须显式按 UTF-8 构造，所以统一走这个函数。
std::filesystem::path fsPath(const std::string& utf8);

// 列出现有存档，返回【文件名】（不含目录），按名字排序（新的在后）。
// 名字里带时间戳，所以字典序 = 时间序。
std::vector<std::string> list();

// ---------------------------------------------------------------------------
//  ★★ "自动产物" vs "你挑好的存档"（2026-09-27 负责人要求）
//
//  ★ 背景
//    无限模式有一句"所有蛇随机搭载 save 里的神经网络"。
//    `saves/` 里其实混着两类文件，语义完全不同：
//
//      ① 训练器【每局覆盖写】的自动产物 —— 不是谁挑出来的"一份网络"：
//           auto_latest.txt       退出训练模式时的自动存档（固定名，每次覆盖）
//           enemy_snapshot.txt    Trainer 每局镜像一份，给 nn-enemy / nn-mate 读
//      ② 玩家/负责人【自己存下来】的存档 —— 这才是"随机搭载"该抽的东西
//
//    负责人明确要求："auto_last 和敌人快照版本神经网络不要同步到 build 里。"
//    把①混进随机池的后果不是崩溃，而是**看起来像没生效**：
//    5 条蛇里有两条抽到同一份自动产物，界面上的"随机"就白做了。
//
//  ★ 为什么做成一个谓词而不是在使用处写两个字符串比较
//    "哪些文件算自动产物"是一条【约定】，将来可能再加（比如加了新的
//    自动镜像名）。写在这里，`GameScene` 只调用它，改的时候只有一处。
// ---------------------------------------------------------------------------
inline bool isAutoGenerated(const std::string& name) {
    return name == kAutoSaveName || name == "enemy_snapshot.txt";
}

// 完整路径（★ 已经是 filesystem::path —— 中文名靠这种类型才能正确落盘）
inline std::filesystem::path path(const std::string& name) {
    return fsPath(std::string(kDir) + "/" + name);
}

// 生成一个带局数与时间戳的文件名，例如：
//     ep000123_20260923_091530.txt
std::string makeName(long episodes);

}  // namespace ckpt
