    double foodScoreUnit = 1.0;

    // -----------------------------------------------------------------------
    //  ⑨ 尸体食物：靠近更快、吃到更多（负责人要求）
    //
    //  ★ 负责人原话："吃/靠近蛇的尸体奖励比食物更高"
    //
    //  ★ 为什么尸体值得更值钱
    //    尸体食物是"击杀的果实"—— 它是击杀的【延迟兑付】。
    //    如果它和普通食物等价，那"杀死对手"就只值一次击杀奖励，
    //    而尸体本身没有额外吸引力，蛇不会主动回头去捡。
    //
    //  ★ 2026-09-26 更新：原来这里写"两处都提高"（靠近系数 + 吃到分值）。
    //    现在**只剩吃到这一处**了 —— 靠近系数 `rApproachCorpse` 已随 ④ 整项删除。
    //    "吃尸体更值钱"仍然成立，由 `corpseScore`（5）> 普通食物（1）
    //    通过 ② 的按分值缩放来表达，不再需要单独的塑形系数。
    //    实测：吃尸体 3.0 × 5/1 = +15.0，吃普通食物 3.0 × 1/1 = +3.0。
    // -----------------------------------------------------------------------
    // -----------------------------------------------------------------------
    //  ④「靠近最近食物」—— 【2026-09-26 整项删除】
    //
    //  ★ 负责人原话："为什么会有这种东西？改掉"
    //    （指的是"刚吃到一个、目标换成更远的"时候 approach 是负数）
    //
    //  ★ 原来的常数
    //        rApproach       = 0.01    靠近普通食物的塑形系数
    //        rApproachCorpse = 0.0167  靠近尸体的塑形系数（1.67 倍）
    //
    //  ★ 为什么删掉（不是"效果不好"，是"逻辑上就是错的"）
    //
    //    它是【差分】项 `k × (上一步距离 − 这一步距离)`，所以"远离食物"必然得负分。
    //    而"吃到食物"这个最该被鼓励的动作，**恰恰必然导致距离变大**
    //    （最近的那个没了 → 目标换成更远的）→
    //    **奖励在同时奖励和惩罚同一个动作。**
    //
    //    旧代码用"目标位置是否相同"打了个补丁跳过那一步，但实测每局
