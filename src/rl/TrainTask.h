    //       完全没有"该往哪走"的指引，只能靠观测里的圈方位/距离。
    //       这是**真实的信息缺口**，应该用观测去补，而不是用一个
    //       会惩罚"吃"的假信号去填。
    // -----------------------------------------------------------------------

    // ---- 学习超参 ----
    // ★ 训练时把关卡缩到"视野能覆盖大半"的小地图，是课程学习的第一步。
    //   负责人可以在「训练设置」里把出生方式改成"均分圆周"配合使用；
