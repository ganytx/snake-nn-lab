//
//  所以：**超参数、奖励、Arena 配置只在这里写一次**，
//  两边都从 TaskConfig 建。
//
//  ★ 这一层不管什么
//
//  · 世界怎么推进   → src/arena/Arena.h
//  · 网络怎么更新   → src/rl/Trainer.h
//  · 怎么记录/显示  → 各自的调用方
