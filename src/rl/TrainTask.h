    //     第 3 次：peak −4.2（= ×10）
    //     第 4 次：peak −12.6（= ×3）
    //     第 5 次（现在）：peak **−63.0**（= ×5，负责人指定"总额 5 倍"）
    //
    //  ★ 与 ⑥′ `escape` 的关系
    //    `rEscape = +1.35` 是【每次事件】的正奖励，量纲不同，不能按数值比。
