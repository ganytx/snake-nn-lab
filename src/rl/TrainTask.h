    //
    //      ① 死亡只罚 −0.5，而"墙边每帧 −0.5"一秒就 −30
    //         → **撞死是止损**，最优策略变成"早点死"
    //      ② 六项塑形全是差分 k·(prev−cur)，整局望远镜求和只剩
    //         k·(首距离−末距离)，**中间路径全部抵消** → 教不会"怎么走"
    //      ③ 目标是"最近的那一个食物"，吃掉它 → 换成更远的 → 距离跳变
    //         → 差分大负数（实测扣 2.6~7.2），而 eat 只给 +1.0
    //         → **吃食物净收益为负**
    //
    //    完整分析与数据见 docs/90-奖励机制.md。
    //
    //  ★ 新机制只有 4 项（负责人定稿）：
    //      ① 死亡       扣很多很多分
    //      ② 吃到食物   加很多分
    //      ③ 快饿死     扣少量分（不要太大）
    //      ④ 靠近最近食物 加少量分（不要太大）
    //
    //  ★ 刻意【没有】的东西，以及为什么：
    //      · 没有存活奖励 —— 它奖励的是"耗时间"而不是"做事"，
    //        是把策略钉死在苟活上的主因
    //      · 没有墙体惩罚 —— 墙的代价由"死亡重罚"表达（负责人明确要求）
    //      · 没有蛇危险区 / 包围奖励 —— 同上
    // -----------------------------------------------------------------------

    // ① 死亡：扣很多很多分
    //
    //   判据：**死亡必须让整局努力白费，且严格劣于任何其它选择。**
    //   一局能赚的上界（ZoneMini：900 帧、吃 6 个）≈ 3.0×6 = +18。
    //   −10 相当于"吃掉 3.3 个食物全部作废"。
    //   它保证旧世界那条"撞死止损"的理性策略在这里是**严格亏本**的。
    double rDie = -10.0;

    // ② 吃到食物：加很多分
    //
    //   判据：**它必须是唯一的、且压倒性的正收益来源。**
    //
    //   ★ 2026-09-26 修正：这里原写"对照 ④ 靠近食物每帧最多 +0.042"，
    //     而 **④ 已经整项删除**，所以那条对照不再存在。改成和【饥饿】对照，
    //     因为饥饿现在才是唯一持续扣分的项：
    //
    //        吃一个普通食物      = +3.0（一次性）
    //        饿着（封顶）        = −3.0/秒   → **吃一个 = 买回 1.0 秒**
    //        饿着 + 原地转圈     = −6.0/秒   → **吃一个 = 买回 0.5 秒**
    //
    //     ⚠️ 这个"买回多少秒"就是本奖励体系的核心判据：
    //        它必须 ≥ 蛇"找到一个食物实际要花的秒数"，否则觅食在算术上就是亏的。
    //        算这个比值之前，务必先确认 `foodScoreUnit` 是对的
    //        （2026-09-26 之前它错成 3.0，导致吃一个实际只给 +1.0）。
    double rEat = 3.0;

    // ③ 快饿死：扣分，**越饿扣越多**，但封顶（10 秒窗口）
    //
    //   ★ 线性加深：剩余 10s 时 0，越接近 0 扣得越狠，饿死那一刻封顶。
    //   ★ 上限 `rHungerMax = -3.0` 是刻意取小的 ——
    //     饿死那一刻本来就有【死亡 −10】，如果饥饿也爬到 −10，
    //     那一刻总扣 −20，会把死亡罚的相对分量稀释掉。
    //     −3 让"饿着"始终是【次要】压力，主要压力来自"会死"。
    //   ★ 用【恒定每帧】而不是旧版的"剩余时间的差分"：
    //     差分形式在"吃到食物"那一刻会因为饥饿值跳变而产生假信号，
    //     而且它在整局上同样会望远镜抵消。恒定扣分语义更直白。
    double rHungerMax    = -3.0;   // 饥饿扣分的上限（饿死那一刻的每帧扣分）
    double hungerWarnSec = 10.0;   // 剩余少于这么多秒才开始扣（秒）

    // ④ 靠近最近食物 —— 【2026-09-26 整项删除，常数 rApproach / rApproachCorpse 已移除】
    //
    //  原值：rApproach = 0.01，rApproachCorpse = 0.0167
    //  删除理由见本文件后面「④ 靠近最近食物 —— 整项删除」那一段的完整说明。
    //  一句话：它是差分项，"远离食物"必然得负分，而"吃到食物"必然导致
    //  目标换成更远的 → **奖励在同时奖励和惩罚同一个动作**。

    // ⑤ 吃饱后的余韵：吃到食物后的一段时间里【持续】加分，而且越来越少
    //
    //   ★ 为什么要有它（负责人提的）
    //     "吃完食物后 10s 改加分，加分越来越少" ——
    //     这等于把"吃饱"变成一段【随时间衰减的满足感】，
    //     而不是吃到那一瞬间的一次性分数。
    //     它天然鼓励【持续进食】：余韵快没了就该再去找一个。
    //
    //   ★ 公式：吃到后立即拿满 rFedMax，然后线性衰减到 0
    //        每秒加分 = rFedMax × (剩余余韵秒数 / fedDuration)
    //     例（rFedMax = 5、fedDuration = 10）：
    //        刚吃到 → 0.5/秒      5 秒后 → 0.25/秒      10 秒后 → 0
    //
    //   ★ 单个食物的满额总收益 = 吃(+3.0) + 余韵(最多 +5.0) = +8.0
    //     它【压过】饥饿上限（−3）—— 所以"去吃"永远优于"饿着"。
    //
    //   ★ 时间来源：用的是 `p.self.hungerLeft`（Arena 算好的剩余饥饿时间），
    //     它每吃一口就重置成满值。所以"余韵"=
    //     `hungerLeft − (饥饿总时长 − fedDuration)`，不需要另存计时器。
    //    ★ 2026-09-26 负责人要求降到**一半**：5.0 → 2.5
    //
    //      理由：实测 `fed` 占了总回报的 **57~72%**，是绝对主导项，
    //      而它奖励的是"喂饱后的时间"而不是"做事"，主导度过高会把
    //      `eat`（真正的目标）淹没。降一半是为了削弱它的相对权重。
    //
    //      ⚠️ 副作用要记住：`fed` 也是当前**唯一在防止锁死**的正信号
    //        （消融实验证明：关掉它会让策略永久锁死在熵 0.169）。
    //        所以它降到 2.5 之后要**重新看锁死率**是不是上升了。
    double rFedMax     = 2.5;      // 刚吃到时每秒的余韵加分（原 5.0）
    double fedDuration = 10.0;     // 余韵持续多少秒（秒）

    // -----------------------------------------------------------------------
    //  ⑥⑦ 贴近敌方身体 / 猎杀优势（负责人要求，2026-09-24）
    //
    //  ★ 负责人原话
    //    "进入敌人身体周围惩罚（大概 3 节体长的大小，比 5s 时的饥饿严重一点，
    //      越近惩罚越严重）；敌人头部进入自己身体部位周围有奖励
    //      （和惩罚的数值相等）"
    //
    //  ★ 为什么这两个量必须【分开算】（这是关键）
    //
    //    规则是「**我的头**碰到**对方的身体**才死」。所以"贴近"有两层
    //    完全相反的含义：
    //        我的头 → 对方身体 ：**危险**，要躲          （⑥′ 逃生奖励）
    //        对方头 → 我的身体 ：**优势**，要利用        （⑦ 奖励）
    //    用"两蛇中心距"或"头到头"当代理，会把这两件事混成一个信号 ——
    //    结果既惩罚了危险、也惩罚了包围。
    //
    //    感知层已经把这两个量都算好了（`Perception::headToEnemyBodyDist`
    //    与 `enemyHeadToMyBodyDist`），而且**队友不算敌方**（队友可穿过）。
    //
    //  ★ 量级
    //    饥饿封顶            −0.05/帧
    //    贴到敌身（旧版满额） −0.15/帧  ← 【2026-09-26 已删除】，改成事件式逃生奖励，见下
    //    逃生奖励            +0.15/次
    //
    //  ⚠️ ⑦ 的效果未验证 —— 负责人决定"效果差了再次删除"。
    //     判据：训练面板的 `escape`（⑥′）与 `hunt`（⑦）两栏是否有非零读数，
    //     以及死亡原因里"撞蛇"的比例是否下降。
    // -----------------------------------------------------------------------
    // -----------------------------------------------------------------------
    //  ★★★ ⑥′ 逃生奖励（2026-09-26 负责人决定，取代原来的每帧贴敌身惩罚）
    //
    //  ★ 负责人原话
    //    "贴近敌方身体的惩罚删掉吧。但是离敌方太近，成功离开给奖励。"
    //
    //  ★ 为什么"位置惩罚"换"事件奖励"是对症的（不只是换个说法）
    //
    //    旧的 `rSnakeDanger` 是**每帧**扣分：蛇只要**待**在危险区里就一直扣，
    //    而"待着"这件事**无法归因到具体某一步** —— 每一步都在扣，梯度被摊平。
    //    再加上观测里原来没有敌人通道，蛇被一个【看不见来源的信号】推着走。
    //
    //    改成"离开才结算"之后，信号只出现在「危险→安全」这个**转变点**，
    //    而转变点是**可以归因到具体动作的**（就是那一步转向）。
    //
    //  ★ 实现：硬阈值 + 迟滞（负责人选的方案乙）
    //
    //        进入 100px  → 标记「危险中」
    //        退回 150px  → 结算 +rEscape，清除标记
    //        每次进入只结算一次 → 蹭边界无法刷分
    //
    //  ★ 为什么必须迟滞（进出用两个不同的阈值）
    //    单一阈值下，蛇在边界上蹭来蹭去会**反复触发**"离开" → 刷分。
    //    迟滞让进出是两道不同的门，来回蹭不再产生任何奖励。
    // -----------------------------------------------------------------------
    //    ★ 2026-09-26 负责人要求提到**三倍**：0.15 → 0.45
    //
    //      理由：实测它触发率极低（0.59 次/局），
    //      0.15 × 0.59 ≈ **0.089 分/局**，只占总回报（≈30 分）的 **0.3%** ——
    //      低三个数量级，等于不存在。提到 0.45 后约 0.27 分/局（≈0.9%），
    //      仍然偏小但至少不再是"完全不可测量"。
    //
    //      ⚠️ 提醒：触发率低本身另有原因（`Perception` 的距离字段每帧没重置，
    //        导致"退出"条件永不成立）—— 那个 bug 已单独修掉，
    //        见 `Perception::resetFrameState()`。所以 0.45 是在**修好之后**的单价。
    double rEscape        = 1.35;   // 每次成功脱离"曾靠近敌人"状态的奖励（原 0.15 → 0.45 → 1.35）
    // ★ 阈值：100 → 250（2026-09-26 负责人要求"放大阈值让它容易触发"）
    //
    //  ★ 为什么必须放大 —— 实测
    //    删掉"每帧贴敌身惩罚"之后，**蛇再也不靠近敌人了**：
    //    危险区生效帧占比从 13~17% 直接掉到 **0.00%**，
    //    逃生奖励 **800 局触发 0 次** —— 规则在实现上是对的，但**是死的**。
    //    原因：逃生奖励的前提是"先进入 100px 内"，而进都没进过。
    //
    //  ★ 250px 的语义变化（必须说清，这不是"同一个规则换个数"）
    //    100px 是"贴到敌身"的真危险距离；250px 已经不危险了，
    //    所以这条规则的语义从"成功脱离危险"变成 **"曾经靠近过敌人"**。
    //    这是负责人明确选择的取舍（宁可语义宽松，也要它真的触发）。
    //
    //  ★⚠️ 但 250px 引出一个新的观测约束
    //    `headToEnemyBodyDist` 只在**视野内**（≈512px）有效，视野外是哨兵 1e9。
    //    250px < 512px，所以【进入】判定是准确的（能真看到才算靠近）。
    //    但【离开】判定（375px）也仍在 512px 内，同样准确。
    //    → 两个阈值都在视野内，这个放大是安全的。
    float  escapeEnterDist = 250.0f; // 进入"曾靠近敌人"状态的距离阈值（像素）
    float  escapeExitRatio = 1.5f;   // 离开阈值 = 进入 × 这个倍数（迟滞宽度），375px

    // -----------------------------------------------------------------------
    //  ★★★ ⑩′ 【饥饿时】位移不足惩罚（2026-09-26 负责人要求，取代"连续转弯惩罚"）
    //
    //  ★ 负责人原话
    //    "把持续转圈的惩罚删掉，改成在饥饿时间（也就是 <10s）时，
    //      3s 内总位移小于一定长度持续扣分（和饥饿扣分相同）。"
    //
    //  ★ 为什么换掉"连续同向转弯惩罚"（⑩，已删除）
    //
    //    ⑩ 的判据是"5 秒内一直同方向转弯"。实测它在 5 个种子上
    //    **触发 0 帧** —— 因为锁死态的实际形态是**直行**（熵 0.171、直行 0.97），
    //    不是绕圈。**那条机制测的是一个当时不存在的动作模式。**
    //
    //    新机制不再猜"刻板行为长什么样"，而是直接看**结果**：
    //        "你饿了，而且你这 3 秒几乎没动"
    //    这个判据同时覆盖绕圈与直行两种锁死形态（只要它们没能觅到食）。
    //
    //  ★ 判据（两个条件【同时】成立）
    //      ① 剩余饥饿 < hungerWarnSec（10 秒）—— 已进入饥饿窗口
    //      ② 最近 dispWindowSec（3 秒）内的**【净位移】** < dispMinPx
    //
    //    ★ ① 为什么必须带"饥饿"这个前提（这是设计的关键）
    //      没有它的话，"慢慢巡逻找食物"也会被罚 —— 那是正常且必要的探索。
    //      加上"已经饿了"这个前提，语义就变成：
    //      **"你都快饿死了，却还在原地打转"** —— 那时候确实该罚。
    //
    //    ★★ ② 为什么必须是【净位移】而不是【总路径长度】
    //
    //      ⚠️ 我第一版用的就是"每帧位移的累加"（路径长度），**这是错的**：
    //        **蛇只要在动，绕一圈的路径长度就有 750px** ——
    //        于是"一直绕圈"必然通过"路径 ≥ 阈值"的检查，**惩罚永远不会触发**。
    //        实测结果：`disp` 恒为 0。
    //
    //      ★ 负责人指出："不应该检测移动总距离（一直绕圈也能满足），
    //        而应该检查总位移，或一段时间平均坐标的偏移。"
    //
    //      ★ 现在用【平均坐标偏移】：把窗口的坐标样本分前后两半各求平均，
    //        净位移 = 两个平均坐标之间的距离。
    //          绕圈    → 平均值几乎不动 → 净位移 ≈ 0  → **正确触发**
    //          直线赶路 → 平均值明显平移 → 净位移大    → 不触发
    //        用"平均"而不是"首尾两点"，是为了不被单帧位置噪声骗到。
    //
    //  ★ 强度：与饥饿封顶相同（−3.0/帧）
    //      于是"饿着且没换地方"时两项叠加 −6.0/帧 —— 明显但不致命
    //      （死亡是 −10 一次性，而且会让整局努力白费）。
    //
    //  ⚠️ 三个常数里只有 `dispWindowSec = 3s` 和"与饥饿相同"是负责人给的，
    //     `dispMinPx` 是我取的（理由见下），觉得不对直接改。
    // -----------------------------------------------------------------------
    double dispPenalty    = -3.0;    // 触发后的每帧扣分（与 rHungerMax 同档）
    double dispWindowSec  = 3.0;     // 看最近多少秒的位移（负责人指定 3s）
    // ★ 3 秒内【净位移】至少要达到多少像素，才算"真的换了地方"
    //
