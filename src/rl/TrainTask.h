    int   corpseScore           = 5;

    // -----------------------------------------------------------------------
    //  ★★★ 奖励机制（2026-09-24 全量重写）
    //
    //  ★ 为什么整段删掉重写，而不是继续调参
    //
    //    旧机制有 8 个机制、11 个常数，实测总回报里 99.66% 来自一个
    //    【哨兵值 bug】（sqrt(1e9)=31622.8 混进了差分），
