    //
    //  ★ 现在生效的曲线（B = −63.0、p = 3、range = 150px）
    //
    //        d=150px（刚进区） → 0
    //        d=100px          → −2.33 /帧（ −140/秒）     = 旧值 ×5
    //        d= 75px          → −7.88 /帧（ −473/秒）     = 旧值 ×5
    //        d= 50px          → −18.67/帧（−1120/秒）     = 旧值 ×5
    //        d= 25px          → −36.46/帧（−2188/秒）     = 旧值 ×5
    //        d= 18px（碰撞）  → −42.93/帧（−2576/秒）     = 旧值 ×5
    //
    //  ★ 标定（逐帧求和，最接近实现）
    //        旧：B −12.6、p 3  →  撞墙总额 −72.37
    //        新：B −63.0、p 3  →  撞墙总额 **−361.83**  = 恰好 5.000 倍 ✓
    //    ⚠️ 加速时穿越只要 0.33 秒 → 该值约减半。
    //
    //  ★★★ 历史（五次调整，前两次是我算错）
    //     第 1 次：线性 + peak −0.25 → 实测每局只 0.05（线性做不到 −5）
    //     第 2 次：改幂曲线，但 peak 写成 **−0.42（少了 10 倍）**，
