    //    · 原地方向掉头只需 2×最小转弯半径 + 头半径 ≈ 80px，够用
    //    · ⚠️ 加速时（450px/s）只有 0.33 秒 —— 容错更小
    //    · 出生点离墙最近 200px（`spawnMargin = 200`），开局不在扣分区内
