    float  dispMinPx      = 120.0f;

    // -----------------------------------------------------------------------
    //  ⑪ 危险距离扣分（墙 / 敌身）—— 负责人要求，2026-09-26 深夜新增
    //
    //  ★ 负责人原话
    //    "现在我们加上危险距离扣分试试（墙，头距离敌人身体），
    //      扣分大小比逃逸多一些" / "越近扣分越多，线性增加"
    //    "选 1，但是墙和敌人身体都是 150px 危险距离。-0.5 每帧先试试"
    //
    //  ★ 公式（两项独立，可同时生效）
    //
    //      墙  ： 头到最近边界的垂直距离 dw < wallDangerDist
    //             → 每帧 rWallDanger  × (1 − dw / wallDangerDist)^power
    //      敌身： headToEnemyBodyDist de < enemyDangerDist
    //             → 每帧 rEnemyDanger × (1 − de / enemyDangerDist)^power
    //
    //    ★★ 是【幂曲线】不是线性（power 默认 3）—— 理由见下面那一段，
    //       一句话：范围锁死 150px 时，线性给不出"撞一次 −5"。
    //
    //  ★ 为什么是"每帧"而不是"每次事件"
    //    撞墙/撞蛇的后果是【一次性 −10 且局终】，那只教"别撞"，
    //    教不了"该提前多远开始躲"。每帧连续扣分把"危险程度"变成
    //    一个连续的距离信号 —— 越近越亏，且**在撞上之前**就生效。
    //
    //  ★ 曲线：peak × (1 − d/dangerDist)^power   ← ★★ 不是线性！见下
    //
    //  ★★★ 2026-09-26 深夜第二次调整（实测驱动）
    //
    //    第一版是【线性】+ peak −0.5。实测面板上 `wall(11) 0.05`、
    //    `enemy(11) 0.05` —— **最小的两项**。
    //    原因：范围锁 150px 时蛇穿过危险区只要 0.6 秒 = 36 帧，
    //    线性下每局总额 = ½ × peak × 36/60，peak −0.25 只有 −0.075。
    //    而"提前绕开"要多走 2 秒 = 饥饿 −1.2 →
    //    **线性下"撞上去"比"绕开"便宜，给不出躲避的梯度。**
    //
    //  ★ 负责人的要求
    //      "不要改范围（允许存在贴边的高难动作），但是太近了要痛
    //       （就像走钢丝一样紧张），我要求如果是撞死，那么这个扣分
    //       能达到 -5 左右"
    //
    //  ★ 两个要求合起来 = 必须非线性
    //    线性要撞一次 −5 得 peak ≈ −16.7/帧，那在 150px 处就痛得离谱。
    //    改三次方后：外面几乎无感、贴脸剧痛 —— 正是"走钢丝"。
    //
    //  ★★★ 2026-09-26 深夜第五次调整：**整条曲线等比 ×5**
    //
    //  ★ 负责人的要求
    //      "你给危险地带乘法扣分设计的更陡峭一些，全面高于原来的扣分，
    //       一直到撞上去这个过程整体的总扣分是原来总扣分的五倍。"
    //
    //  ★★ 这三个要求合起来【只有唯一解】—— 这条推导必须留着，否则以后还会再试错
