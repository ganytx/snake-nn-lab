    //  ★ 为什么视野外不扣分是安全的
    //    敌身距离来自 `Perception::headToEnemyBodyDist`，**只在视野内算**
    //    （超出是哨兵 1e9）。150px 远小于视野 512px → 不会漏判危险。
    // -----------------------------------------------------------------------
    double rWallDanger      = -210.0;  // ⑪ 贴墙时的每帧扣分（满额，贴脸）★ 2026-09-28: -21 → -210 (×10)
    float  wallDangerDist   = 150.0f;  // 墙的危险距离（像素）
    double rEnemyDanger     = -210.0;  // ⑪ 头贴敌身时的每帧扣分（满额，贴脸）★ 2026-09-28: -21 → -210 (×10)
    float  enemyDangerDist  = 150.0f;  // 敌身的危险距离（像素）

