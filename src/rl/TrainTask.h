    //    设新曲线 = B·u^p（u = 1 − d/150），要求：
    //        ① 撞墙总额 = 5 × 原总额
    //        ② 对 ∀u ∈ [u_hit, 1]：|B|·u^p ≥ 12.6·u³   （全面高于）
    //
    //    对每个 p 解出满足 ① 的 B，再检查 ② —— 实测结果（逐帧求和校准）：
    //
    //        p    B        总额      最低比值（危险区最外缘）   全面高于?
    //        3    −63.00   −361.83   5.000                    ✅
    //        4    −88.13   −361.83   0.132                    ❌ 在 147px 处跌到 0.13
    //        5   −118.35   −361.83   0.003                    ❌
    //        9   −309.70   −361.83   0.000                    ❌
    //       12   −565.18   −361.83   0.000                    ❌
    //
    //    **只有 p = 3 能同时满足两条。** 原因是幂函数的数学必然：
