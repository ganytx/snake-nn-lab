#pragma once

// ============================================================================
//  activation.h — 激活函数及其导数
//
//  ★★★ 全库最重要的约定：★★★
//      所有导数函数 d*(z) 的输入都是【激活前的 z】（也叫 logit / 预激活值），
//      而不是激活后的输出 a。
//
//  为什么必须统一？看你原来那份 network.h：
//      dReLU(x)    = x > 0 ? 1 : 0      ← 这里 x 必须是【激活前的 z】
//      dsigmoid(x) = x * (1 - x)        ← 这里 x 必须是【激活后的 a = σ(z)】
//  两个导数对"输入是什么"的约定正好相反，所以想用一个 dAF 模板参数
//  把 ReLU 和 sigmoid 统一起来是做不到的 —— 这不是写法问题，是语义矛盾。
//
//  统一成"输入 z"之后：
//      dReLU(z)    = z > 0 ? 1 : 0
//      dsigmoid(z) = σ(z) * (1 - σ(z))     ← 内部自己再算一次 σ(z)
//  代价是 dsigmoid 多算一次 exp()，换来的是整个库的接口一致、不会用错。
//
//  另一个必须记住的点：链式法则里乘的是 dL/dz，不是 dL/da。
//      delta = (∂L/∂a) ⊙ dAF(z)
//  如果误把激活后的 a 传进 dAF，训练不会报错，只会"学得很差"——
//  这是最典型、最难查的一类 bug。
// ============================================================================

#include <cmath>

namespace nn {

// ---------------------------------------------------------------------------
// ReLU：f(z) = max(0, z)
// 优点：正区间导数恒为 1，梯度不会衰减，是深层网络的默认选择
// 缺点：负区间导数恒为 0，神经元一旦"死掉"就再也回不来（dead ReLU）
// ---------------------------------------------------------------------------
inline double relu(double z) { return z > 0.0 ? z : 0.0; }
inline double drelu(double z) { return z > 0.0 ? 1.0 : 0.0; }

// ---------------------------------------------------------------------------
// Sigmoid：f(z) = 1 / (1 + e^(-z))
// 输出范围 (0, 1)，可以当概率用
// 缺点：输出不是零中心的（全是正数），且两端导数趋近 0 → 梯度消失
// ---------------------------------------------------------------------------
inline double sigmoid(double z) {
    // 数值稳定写法：z 很负时 exp(-z) 会溢出成 inf，1/(1+inf) = 0，不会产生 NaN
    return 1.0 / (1.0 + std::exp(-z));
}
inline double dsigmoid(double z) {
    const double s = sigmoid(z);
    return s * (1.0 - s);      // 注意：这里传入的是 z，s 是内部算出来的
}

// ---------------------------------------------------------------------------
// Tanh：f(z) = (e^z - e^(-z)) / (e^z + e^(-z))
// 输出范围 (-1, 1)，零中心，比 sigmoid 好训练
// 小网络、教学实验里最省心的选择
// ---------------------------------------------------------------------------
inline double tanhAct(double z) { return std::tanh(z); }
inline double dtanhAct(double z) {
    const double t = std::tanh(z);
    return 1.0 - t * t;
}

// ---------------------------------------------------------------------------
// 恒等映射：f(z) = z
// 输出层做回归、或者输出 logits（后面自己接 softmax）时用
// ---------------------------------------------------------------------------
inline double identity(double z) { return z; }
inline double didentity(double) { return 1.0; }

}  // namespace nn
