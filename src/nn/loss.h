#pragma once

// ============================================================================
//  loss.h — 损失函数 + softmax + 交叉熵
//
//  神经网络训练的三件套：
//      前向传播 → 算损失 → 反向传播求梯度 → 更新权重
//  这里是中间的"算损失"和"损失对输出层的梯度"。
//
//  一个关键设计：本库的 MLP 输出层是【线性的】（不加激活函数），
//  直接吐出 logits（未归一化的分数）。这样同一套网络可以：
//      · 接 MSE       → 做回归 / 行为克隆
//      · 接 softmax   → 做多分类 / 强化学习的策略
//  加激活函数是"外面"的事，网络本身保持通用。
// ============================================================================

#include "matrix.h"
#include <cmath>
#include <algorithm>

namespace nn {

// ===========================================================================
//  均方误差 MSE：L = (1/N) · Σ (y_i - t_i)²
//  适合：回归问题、连续动作、行为克隆
// ===========================================================================
template <typename T, int N>
T mseLoss(const vec<T, N>& y, const vec<T, N>& t) {
    T acc = T();
    for (int i = 0; i < N; ++i) {
        const T d = y.a[i] - t.a[i];
        acc += d * d;
    }
    return acc / T(N);
}

// MSE 对网络输出 y 的梯度：∂L/∂y = 2(y - t)/N
// 注意：这个梯度是"损失对输出层【激活前】的值"的梯度，
//       因为 MLP 输出层是线性的（y == z），两者恰好相同。
template <typename T, int N>
vec<T, N> mseGrad(const vec<T, N>& y, const vec<T, N>& t) {
    vec<T, N> g;
    for (int i = 0; i < N; ++i) g.a[i] = T(2) * (y.a[i] - t.a[i]) / T(N);
    return g;
}

// ===========================================================================
//  Softmax：把任意实数向量压成概率分布
//
//      p_i = e^(z_i) / Σ_j e^(z_j)
//
//  数值稳定技巧：先减掉最大值再取 exp。
//  因为 e^z 在 z=800 左右就会溢出成 inf，减掉 max 之后
//  最大的指数变成 e^0 = 1，其余 ≤ 1，永远不会溢出，
//  而数学结果完全不变（分子分母同乘 e^(-max)）。
// ===========================================================================
template <typename T, int N>
vec<T, N> softmax(const vec<T, N>& z) {
    T mx = z.a[0];
    for (int i = 1; i < N; ++i)
        if (z.a[i] > mx) mx = z.a[i];

    vec<T, N> p;
    T total = T();
    for (int i = 0; i < N; ++i) {
        p.a[i] = std::exp(z.a[i] - mx);
        total += p.a[i];
    }
    for (int i = 0; i < N; ++i) p.a[i] /= total;
    return p;
}

// ===========================================================================
//  交叉熵损失：L = -log( p[action] )
//
//  直觉：给"正确答案"分配的概率越接近 1，损失越接近 0；
//        越接近 0，损失越大（-log(0) → +∞）。
//  这就是"让网络对正确动作越来越自信"的数学表达。
//
//  加 1e-12 是为了防止 log(0) = -inf 把整个训练污染成 NaN。
// ===========================================================================
template <typename T, int N>
T crossEntropyLoss(const vec<T, N>& p, int action) {
    const T safe = std::max(p.a[action], static_cast<T>(1e-12));
    return -std::log(safe);
}

// ===========================================================================
//  ★ softmax + 交叉熵 的梯度化简 —— 推导一次，受益终身
//
//  设 z 是 logits，p = softmax(z)，损失 L = -log(p_a)（a 是正确动作下标）。
//  如果老老实实按链式法则算，需要先求 ∂L/∂p，再求 softmax 的雅可比矩阵
//  ∂p/∂z（一个 N×N 矩阵），再相乘 —— 又慢又容易错。
//
//  但这两步乘起来会神奇地化简成极其干净的结果：
//
//      ∂L/∂z_i = p_i - 1{i == a}
//
//  也就是：「预测概率」减去「one-hot 标签」。
//  这就是为什么几乎所有分类网络都用 softmax + 交叉熵这一对组合：
//  输出层的误差项直接就是"预测 − 真值"，和 MSE 长得一模一样。
//
//  这个公式是后面 REINFORCE 策略梯度的基石：
//  策略梯度需要 ∂(-log π(a|s))/∂logits，正好就是它。
// ===========================================================================
template <typename T, int N>
vec<T, N> softmaxCrossEntropyGrad(const vec<T, N>& p, int action) {
    vec<T, N> g = p;
    g.a[action] -= T(1);
    return g;
}

// ===========================================================================
//  argmax：取出最大元素的下标
//  策略网络"选动作"时用，也用来算准确率
// ===========================================================================
template <typename T, int N>
int argmax(const vec<T, N>& v) {
    int best = 0;
    for (int i = 1; i < N; ++i)
        if (v.a[i] > v.a[best]) best = i;
    return best;
}

}  // namespace nn
