# ===========================================================================
#  sync_saves.ps1 -- copy the user's chosen saves from saves\ into build\saves\
#
#  WHY THIS SCRIPT EXISTS (do not inline this logic back into CMakeLists.txt)
#
#    The first attempt used file(GLOB) + add_custom_command(copy_if_different)
#    with the file paths written into the generated Makefile. On this machine
#    cmake runs under the **GBK** code page, so the non-ASCII (Chinese) file
#    names got transcoded into mojibake inside build.make. The build then died
#    at the POST_BUILD step with something like:
#
#        Error copying file (if different) from ".../saves/<mojibake>.txt"
#
#    (The real message contained a literal '?' where two bytes could not be
#    mapped back -- that '?' is the signature of a lossy code page conversion.)
#
#    The lesson: **never let the build system put a non-ASCII file name on a
#    command line.** Let PowerShell enumerate the directory instead -- it reads
#    the real directory entries from the filesystem, so the names never pass
#    through any code page conversion.
#
#  WHY the script itself is pure ASCII
#    Windows PowerShell 5.1 reads a .ps1 file WITHOUT a BOM as ANSI (GBK here),
#    so a UTF-8 Chinese comment inside this file would be mangled -- the same
#    class of bug as above, just one layer up. All Chinese explanation
#    therefore lives in CMakeLists.txt (which cmake reads as UTF-8).
#    **Keep this file ASCII-only.** The save file names themselves are Chinese
#    and that is fine -- they are read from the filesystem at runtime, never
#    written into this file.
#
#  WHICH FILES ARE EXCLUDED, AND WHY (requested by the project owner)
#
#    auto_latest.txt       the trainer's "latest progress" autosave (fixed name,
#                          overwritten every time training exits)
#    enemy_snapshot.txt    the frozen snapshot mirrored by the trainer every
#                          episode; read BY FIXED NAME by the "nn-enemy" and
#                          "nn-mate" brains
#
#    Neither one is a network the owner picked out. If they enter the random
#    pool used by Infinite mode ("every snake loads a random saved network"),
#    several snakes draw the same file and the randomness looks broken.
#
#    NOTE: only *copying* is skipped. This script never deletes anything in
#    build\saves\, so the runtime copies of those two files stay where the
#    game and the trainer expect them.
#
#  USAGE (called automatically as a POST_BUILD step of snake_game)
#    powershell -NoProfile -ExecutionPolicy Bypass -File tools\sync_saves.ps1 ^
#               -SourceDir <repo>\saves -DestDir <repo>\build\saves
# ===========================================================================

param(
    [Parameter(Mandatory = $true)][string]$SourceDir,
    [Parameter(Mandatory = $true)][string]$DestDir
)

$ErrorActionPreference = 'Stop'

# ---- The two auto-generated files that must NOT be synced -----------------
# Keep this list in sync with ckpt::isAutoGenerated() in src/rl/Checkpoint.h --
# that function is the same rule applied to the *random pool* at runtime.
$excluded = @('auto_latest.txt', 'enemy_snapshot.txt')

if (-not (Test-Path -LiteralPath $SourceDir)) {
    Write-Host "[sync_saves] no source dir: $SourceDir (nothing to do)"
    exit 0
}

if (-not (Test-Path -LiteralPath $DestDir)) {
    New-Item -ItemType Directory -Path $DestDir -Force | Out-Null
}

$files = Get-ChildItem -LiteralPath $SourceDir -Filter '*.txt' -File
$copied = 0

foreach ($f in $files) {
    if ($excluded -contains $f.Name) { continue }

    # -LiteralPath: the name may contain [ ] etc. which would be treated as
    # wildcards by the plain -Path parameter.
    Copy-Item -LiteralPath $f.FullName -Destination $DestDir -Force
    $copied++
}

Write-Host "[sync_saves] $copied save(s) synced to $DestDir (excluded: $($excluded -join ', '))"
exit 0
